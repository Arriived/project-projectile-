// Generates migrations/APPLY-ALL.sql by CONCATENATING the numbered migrations in order.
//
// ── WHY THIS IS GENERATED RATHER THAN HAND-MAINTAINED ─────────────────────────
//
// The previous APPLY-ALL.sql was written by hand and had drifted badly by the time anyone
// diffed it against the files it claims to bundle:
//
//   * It contained NO base schema at all -- zero CREATE TABLE -- while its own header said
//     "THIS FILE IS FOR A FRESH DATABASE". On a genuinely fresh database its first
//     statement (ALTER TABLE public.tokens) fails on a table that does not exist.
//   * It was missing all of migration 004: both `trades.virtual_*_reserves` columns, the
//     `token_candles_1m` view, that view's GRANT, and the `trades_token_blocktime_idx`
//     index.
//   * It carried a SUPERSEDED version of 003: `tokens.total_supply` where 003 adds
//     `tokens.curve_token_supply`. Those are not the same column, and the difference is
//     the one CLAUDE.md flags as a 1.24x market-cap overstatement -- the LP reserve is not
//     circulating supply.
//
// Twelve objects were missing in total. A hand-maintained bundle of files that are
// themselves the source of truth is a copy that will drift again, so it is no longer
// hand-maintained.
//
// Run: node indexer/scripts/gen-apply-all.js

const fs = require("fs");
const path = require("path");

const DIR = path.join(__dirname, "..", "migrations");
const OUT = path.join(DIR, "APPLY-ALL.sql");

// Explicit order, not a directory glob. A glob would pick up anything dropped in the
// folder, and sort order is exactly what makes that dangerous: `003_ROLLBACK.sql` sorted
// BEFORE `003_list_page_columns.sql` (`R` = 0x52 < `l` = 0x6C), so "apply everything in
// order" ran the rollback first. Rollbacks now live in rollbacks/ and this list is
// explicit so neither problem can recur.
const ORDER = [
  "000_base_schema.sql",
  "001_add_token_state.sql",
  "002_add_creator_launch_disclosure.sql",
  "003_list_page_columns.sql",
  "004_trade_reserves_and_ohlc.sql",
  "005_schema_migrations.sql",
  "006_candle_open_from_previous.sql",
  "007_revoke_view_grants.sql",
];

const HEADER = `-- APPLY-ALL.sql — GENERATED by indexer/scripts/gen-apply-all.js. DO NOT EDIT BY HAND.
--
-- Regenerate with:  node indexer/scripts/gen-apply-all.js
--
-- Bundles every numbered migration, in order, for pasting into the Supabase SQL editor:
--   Project -> SQL Editor -> New query -> paste -> Run
--
-- ⚠⚠ FOR A FRESH DATABASE. Every statement is written to be idempotent (CREATE TABLE IF
-- NOT EXISTS, ADD COLUMN IF NOT EXISTS, CREATE OR REPLACE VIEW, DROP POLICY IF EXISTS),
-- so re-running it is safe -- but read the checkpoint note in 000 before pointing it at a
-- database a live indexer is using.
--
-- ⚠ DDL needs SQL-editor or superuser rights. The service-role key CANNOT run this: it is
-- a PostgREST credential and PostgREST exposes no SQL-execution endpoint (verified against
-- the live project — zero RPC functions).
--
-- AFTER RUNNING THIS, RUN THE VERIFICATION QUERY: migrations/VERIFY-SCHEMA.sql, with the
-- ANON key, not the service key. tokens_with_volume is SECURITY INVOKER, so a missing
-- grant makes it return ZERO ROWS WITH NO ERROR — and an empty token list is also exactly
-- what launch day legitimately looks like. The service key bypasses RLS and cannot tell
-- the two apart.
`;

let out = HEADER;
for (const f of ORDER) {
  const p = path.join(DIR, f);
  if (!fs.existsSync(p)) {
    console.error(`MISSING: ${f} — refusing to generate a partial bundle.`);
    process.exitCode = 1;
    return;
  }
  const body = fs.readFileSync(p, "utf8");
  out += `\n\n-- ${"═".repeat(74)}\n-- ${f}\n-- ${"═".repeat(74)}\n\n${body.trimEnd()}\n`;
}

// The applied-state record. Written LAST so a bundle that fails part-way does not claim
// migrations it did not apply.
out += `

-- ${"═".repeat(74)}
-- applied-state record
-- ${"═".repeat(74)}
--
-- Each numbered migration also stamps its own row (see the tail of each file). This block
-- is the belt-and-braces for a bundle run: it records every version this file contains.
INSERT INTO public.schema_migrations (version) VALUES
${ORDER.map((f) => `  ('${f.slice(0, 3)}')`).join(",\n")}
ON CONFLICT (version) DO NOTHING;
`;

fs.writeFileSync(OUT, out);
console.log(`wrote ${OUT}`);
console.log(`bundled ${ORDER.length} migrations, ${out.split("\n").length} lines`);
