// Generates the React frontend's ABI module from the Hardhat build artifact.
//
// Same reasoning as scripts/gen-indexer-abi.js, which this is modelled on: a
// hand-curated ABI subset falls behind the contract silently. That file's comment
// records the failure -- a Curve tuple listed as 16 fields against a struct that had
// grown to 22, decoded by ethers WITHOUT error because the struct is all-static, so the
// offsets still lined up and the extra fields were simply dropped.
//
// One difference from the indexer's generator, and it is the reason this file exists
// rather than importing the JSON: viem infers argument and return types from the ABI
// only when it is a const-asserted TS literal. `import abi from './x.json'` widens every
// string to `string` and viem falls back to untyped `unknown`, which throws away exactly
// the protection we are here for -- the 18-vs-6 decimal confusion (FRONTEND_BUILD_V2
// rule 9, REACT_REBUILD trap 4) is a bigint/type problem, and typed reads catch a whole
// class of it at compile time.
//
// So the output is a .ts file ending in `as const`. Run after `hardhat compile`.
const fs = require("fs");
const path = require("path");

const ARTIFACT = path.join(__dirname, "..", "artifacts", "contracts", "LFX1.sol", "LFX1.json");
const TOKEN_ARTIFACT = path.join(__dirname, "..", "artifacts", "contracts", "LFX1Token.sol", "LFX1Token.json");
const OUT_DIR = path.join(__dirname, "..", "app", "src", "abi");

function emit(name, abi, sourceNote) {
  return (
    `// GENERATED by scripts/gen-frontend-abi.js -- DO NOT HAND-EDIT.\n` +
    `// Regenerate with: npm run gen:frontend-abi  (wired into npm run build)\n` +
    `//\n` +
    `// ${sourceNote}\n` +
    `// \`as const\` is load-bearing: without it viem cannot infer argument or return\n` +
    `// types and every read degrades to \`unknown\`.\n` +
    `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`
  );
}

function readAbi(file, label) {
  if (!fs.existsSync(file)) {
    throw new Error(`artifact not found at ${file} -- run \`npx hardhat compile\` first`);
  }
  const { abi } = JSON.parse(fs.readFileSync(file, "utf8"));
  if (!Array.isArray(abi) || abi.length === 0) {
    throw new Error(`${label} artifact contains no ABI`);
  }
  return abi;
}

function main() {
  const factoryAbi = readAbi(ARTIFACT, "LFX1");
  const tokenAbi = readAbi(TOKEN_ARTIFACT, "LFX1Token");

  fs.mkdirSync(OUT_DIR, { recursive: true });

  const files = [
    ["lfx1.ts", emit("lfx1Abi", factoryAbi, "Full LFX1 factory ABI, emitted whole -- there is no curated subset to fall behind.")],
    ["lfx1Token.ts", emit("lfx1TokenAbi", tokenAbi, "LFX1Token: OpenZeppelin ERC20 plus metadataURI/creator/factory. decimals() is 18, not overridden.")],
  ];

  for (const [name, content] of files) {
    fs.writeFileSync(path.join(OUT_DIR, name), content);
  }

  const errs = factoryAbi.filter((x) => x.type === "error").length;
  console.log(
    `wrote app/src/abi/lfx1.ts (${factoryAbi.length} entries, ${errs} custom errors) ` +
      `and app/src/abi/lfx1Token.ts (${tokenAbi.length} entries)`
  );
}

main();
